#!/usr/bin/env bash
# Vendors export-forge (https://github.com/maxusify/export-forge) into this addon.
#
# Usage:
#   tools/vendor-export-forge.sh [REF] [SOURCE]
#
#   REF     tag, branch or commit SHA to vendor (default: $EXPORT_FORGE_REF or the pinned one below)
#   SOURCE  git URL or local repository path   (default: $EXPORT_FORGE_SOURCE or the GitHub URL)
#
# Examples:
#   tools/vendor-export-forge.sh                     # re-vendor the pinned version
#   tools/vendor-export-forge.sh v1.2.0              # upgrade to a tag
#   tools/vendor-export-forge.sh dev ~/Projects/export-forge   # test local, committed changes
#
# What it does:
#   * fetches SOURCE at REF into a temp dir (only committed content is used),
#   * copies addons/export_forge/**/*.cs into DEST_DIR, WITHOUT *.uid / *.import files,
#     so the vendored copy never shares UIDs with a standalone export-forge install,
#   * rewrites the namespace so the C# types don't clash with standalone export-forge either,
#   * keeps .uid files Godot already generated for this vendored copy (no churn on re-runs),
#   * records the vendored source and commit in DEST_DIR/VENDORED.md.
set -euo pipefail

# ---- configuration ---------------------------------------------------------
PINNED_REF="v1.1.0"
DEFAULT_SOURCE="https://github.com/maxusify/export-forge.git"
SOURCE_SUBDIR="addons/export_forge"
DEST_DIR="addons/cosineful_palettes/vendor/export_forge"
SOURCE_NAMESPACE="SabishiDev.ExportForge"
TARGET_NAMESPACE="CosinefulPalettes.Vendor.ExportForge"
# ---------------------------------------------------------------------------

REF="${1:-${EXPORT_FORGE_REF:-$PINNED_REF}}"
SOURCE="${2:-${EXPORT_FORGE_SOURCE:-$DEFAULT_SOURCE}}"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="$ROOT/$DEST_DIR"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

echo ">> Fetching $SOURCE @ $REF"
git -C "$TMP" init -q repo
git -C "$TMP/repo" fetch -q --depth 1 "$SOURCE" "$REF"
git -C "$TMP/repo" -c advice.detachedHead=false checkout -q FETCH_HEAD
COMMIT="$(git -C "$TMP/repo" rev-parse HEAD)"

SRC="$TMP/repo/$SOURCE_SUBDIR"
[[ -d "$SRC" ]] || { echo "error: '$SOURCE_SUBDIR' not found in $SOURCE @ $REF" >&2; exit 1; }

# Keep UIDs Godot generated for the previous vendored copy.
UIDS="$TMP/uids"
mkdir -p "$UIDS"
if [[ -d "$DEST" ]]; then
    (cd "$DEST" && find . -name '*.uid' -exec cp --parents {} "$UIDS" \;)
fi

rm -rf "$DEST"
mkdir -p "$DEST"

echo ">> Copying sources into $DEST_DIR"
ns_src="${SOURCE_NAMESPACE//./\\.}"
(cd "$SRC" && find . -type f -name '*.cs') | sort | while read -r f; do
    mkdir -p "$DEST/$(dirname "$f")"
    sed -E "s/\b${ns_src}\b/${TARGET_NAMESPACE}/g" "$SRC/$f" > "$DEST/$f"
    [[ -f "$UIDS/$f.uid" ]] && cp "$UIDS/$f.uid" "$DEST/$f.uid"
    echo "   $f"
done

if grep -rq "$SOURCE_NAMESPACE" "$DEST"; then
    echo "error: '$SOURCE_NAMESPACE' still referenced after rewrite:" >&2
    grep -rn "$SOURCE_NAMESPACE" "$DEST" >&2
    exit 1
fi

# LICENSE from the upstream repo root, if present.
[[ -f "$TMP/repo/LICENSE" ]] && cp "$TMP/repo/LICENSE" "$DEST/LICENSE"

cat > "$DEST/VENDORED.md" <<MD
# Vendored: export-forge

**Do not edit files in this directory by hand.** They are generated by
\`tools/vendor-export-forge.sh\`; change upstream and re-run the script instead.

| | |
|---|---|
| Source | ${DEFAULT_SOURCE} |
| Ref | \`${REF}\` |
| Commit | \`${COMMIT}\` |
| Namespace | \`${SOURCE_NAMESPACE}\` → \`${TARGET_NAMESPACE}\` |

\`.uid\` files are intentionally not copied from upstream, so a project that has both
this addon and export-forge installed does not get duplicate UIDs.
MD

echo ">> Vendored export-forge $REF ($COMMIT)"
